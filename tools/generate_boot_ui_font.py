"""Generate a small monochrome Chinese glyph subset; no runtime font/file I/O."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import argparse,re
p=argparse.ArgumentParser();p.add_argument('--font',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[1]
source=(root/'poc/m3_boot/source/boot_ui.c').read_text(encoding='utf-8')
source+=(root/'poc/m3_boot/source/main.c').read_text(encoding='utf-8')
source+=(root/'poc/m3_boot/source/table_profile.c').read_text(encoding='utf-8')
chars=''.join(chr(i) for i in range(32,127))+''.join(sorted({c for c in source if ord(c)>127}))
font=ImageFont.truetype(str(a.font),24)
out=['/* Generated by tools/generate_boot_ui_font.py. 32x32 monochrome glyphs. */',
     'static const unsigned glyph_codes[]={'+','.join(str(ord(c)) for c in chars)+'};',
     'static const unsigned short glyph_tiles[][64] __attribute__((aligned(8)))={']
for ch in chars:
 im=Image.new('1',(32,32));d=ImageDraw.Draw(im);d.text((0,0),ch,font=font,fill=1)
 vals=[]
 for ty in (0,16):
  for tx in (0,16):
   for y in range(ty,ty+16):
    vals.append(sum((1<<(15-x)) for x in range(16) if im.getpixel((tx+x,y))))
 out.append('{'+','.join(hex(v) for v in vals)+'},')
out.append('};')
(root/'poc/m3_boot/source/boot_ui_font.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('glyphs',len(chars),'bytes',len(chars)*128)
